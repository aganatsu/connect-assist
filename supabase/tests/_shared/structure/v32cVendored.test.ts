Deno.test("V3.2c prefix causality: state and events after bar t equal a fresh run on bars ≤ t", () => {
  for (const pair of SERIES) for (const tf of ["4H", "1H"] as const) {
    const bars = aggregate(tf, hoursOf(pair)).bars;
    const full = run(bars, tf);
    for (let k = 1; k <= 6; k++) {
      const t = Math.floor((bars.length - 1) * k / 6);
      const part = run(bars.slice(0, t + 1), tf);
      assertEquals(JSON.stringify(part.s), JSON.stringify(full.states[t]), `${pair} ${tf} state at ${t}`);
      assertEquals(JSON.stringify(part.store.at(t)), JSON.stringify(full.store.at(t)), `${pair} ${tf} snapshot at ${t}`);
    }
  }
});

Deno.test("V3.2c mirror symmetry: negated prices give the mirrored structure (bull↔bear, high↔low, prices negated)", () => {
  const PRICE_KEYS = new Set(["price", "close", "p100", "p50", "p0"]);
  // word-level swap: values are enums ("bull", "high") or free text ("seed: close above first swing high")
  const SWAP: Record<string, string> = { bull: "bear", bear: "bull", high: "low", low: "high", above: "below", below: "above" };
  const mirror = (v: unknown, key = ""): unknown => {
    if (typeof v === "number") return PRICE_KEYS.has(key) ? -v : v;
    if (typeof v === "string") return v.replace(/\b(bull|bear|high|low|above|below)\b/g, (w) => SWAP[w]);
    if (Array.isArray(v)) return v.map((x) => mirror(x, key));
    if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, mirror(x, k)]));
    return v;
  };
  for (const pair of SERIES) for (const tf of ["D", "4H", "1H"] as const) {
    const hours = hoursOf(pair);
    const neg = hours.map((b) => ({ t: b.t, o: -b.o, h: -b.l, l: -b.h, c: -b.c }));
    const a = run(aggregate(tf, hours).bars, tf), b = run(aggregate(tf, neg).bars, tf);
    assertEquals(JSON.stringify(mirror(b.events)), JSON.stringify(a.events), `${pair} ${tf} events`);
    const pd = (st: State[]) => st.map((s) => premiumDiscount(s));
    assertEquals(JSON.stringify(mirror(pd(b.states))), JSON.stringify(pd(a.states)), `${pair} ${tf} premium/discount`);
  }
});

Deno.test("V3.2c DST boundaries: NY-aligned 4H (17/21/01/05/09/13) and Daily (17:00→17:00) buckets across the 2025 US transitions", () => {
  const H = 3_600_000;
  for (const [from, to] of [["2025-03-05T22:00:00Z", "2025-03-13T21:00:00Z"], ["2025-10-29T21:00:00Z", "2025-11-06T22:00:00Z"]]) {
    const hours: H1[] = [];
    for (let t = Date.parse(from); t < Date.parse(to); t += H) if (fxOpen(t)) hours.push({ t, o: 1, h: 1.001, l: 0.999, c: 1 });
    const h4 = aggregate("4H", hours);
    assertEquals(h4.skipped, [], "every 4H bucket complete on a gap-free week");
    for (const b of h4.bars) {
      assert([17, 21, 1, 5, 9, 13].includes(nyParts(b.t).h), `4H bucket starts at NY ${nyParts(b.t).h}:00`);
      assertEquals(b.closeTime - b.t, 4 * H);
    }
    const d = aggregate("D", hours);
    for (const b of d.bars) { assertEquals(nyParts(b.t).h, 17, "Daily bucket starts at 17:00 NY"); assertEquals(b.closeTime - b.t, 24 * H); }
  }
  // Sunday open after the spring change: 17:00 EDT = 21:00Z, trading day = Monday; the Friday before closes at 17:00 EST = 22:00Z
  assert(fxOpen(Date.parse("2025-03-09T21:00:00Z")) && !fxOpen(Date.parse("2025-03-09T20:00:00Z")));
  assertEquals(tradingDay(Date.parse("2025-03-09T21:00:00Z")), "2025-03-10");
  assert(!fxOpen(Date.parse("2025-03-07T22:00:00Z")) && fxOpen(Date.parse("2025-03-07T21:00:00Z")));
  // Sunday open after the fall change: 17:00 EST = 22:00Z
  assert(fxOpen(Date.parse("2025-11-02T22:00:00Z")) && !fxOpen(Date.parse("2025-11-02T21:00:00Z")));
  assertEquals(bucketKey("4H", Date.parse("2025-11-02T22:00:00Z")), bucketKey("4H", Date.parse("2025-11-03T01:00:00Z")));
});

Deno.test("V3.2c frozen aggregation keeps incomplete buckets skipped (a 22/24-hour Daily and a 2/4-hour 4H bucket are not bars)", () => {
  const H = 3_600_000, start = Date.parse("2025-04-20T21:00:00Z"); // Sunday 17:00 NY (EDT)
  const hours: H1[] = [];
  for (let t = start; t < start + 24 * H; t += H) if (t !== start && t !== start + H) hours.push({ t, o: 1, h: 1.001, l: 0.999, c: 1 }); // first 2 hours absent
  const d = aggregate("D", hours), h4 = aggregate("4H", hours);
  assertEquals(d.bars.length, 0); assertEquals(d.skipped.map((s) => s.hours), [22]);
  assertEquals(h4.bars.length, 5); assertEquals(h4.skipped.map((s) => s.hours), [2]);
});

Deno.test("V3.2c timeframe isolation: independent per-TF states; snapshots are deep-frozen and read-only", () => {
  const hours = hoursOf("SYN-A");
  const dBars = aggregate("D", hours).bars, hBars = aggregate("1H", hours).bars;
  const alone = run(dBars, "D");
  // interleave a 1H state with the Daily state: the Daily result must not change
  let d: State = initState(), h: State = initState(); let j = 0;
  for (const db of dBars) { while (j < hBars.length && hBars[j].closeTime <= db.closeTime) h = step(frozenV32cConfig("1H"), h, hBars[j++]).state; d = step(frozenV32cConfig("D"), d, db).state; }
  assertEquals(JSON.stringify(d), JSON.stringify(alone.s));
  const snap = alone.store.asOf(dBars.at(-1)!.closeTime)!;
  assert(Object.isFrozen(snap) && Object.isFrozen(snap.P as object));
  assertThrows(() => { (snap as { trend: unknown }).trend = "x"; }, TypeError);
  assertEquals(alone.store.asOf(dBars[0].closeTime - 1), null, "a forming / future bar is never visible");
});


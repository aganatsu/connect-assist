const sha256 = async (s: string | Uint8Array<ArrayBuffer>) =>
  [...new Uint8Array(await crypto.subtle.digest("SHA-256", typeof s === "string" ? new TextEncoder().encode(s) : s))]
    .map((b) => b.toString(16).padStart(2, "0")).join("");
const fnSource = (src: string, name: string): string => {
  const start = src.indexOf(`export function ${name}(`);
  if (start < 0) throw new Error(`${name} not found`);
  let depth = 0;
  for (let i = src.indexOf("{", src.indexOf(")", start)); i < src.length; i++) {
    if (src[i] === "{") depth++;
    else if (src[i] === "}" && --depth === 0) return src.slice(start, i + 1);
  }
  throw new Error(`${name}: unbalanced braces`);
};

const GOLDEN = JSON.parse(Deno.readTextFileSync(`${ROOT}tests/fixtures/v32c/golden_v32c.json`));
const SERIES = Object.keys(SYNTHETIC_SERIES); // "SYN-A", "SYN-B"
const hoursOf = (name: string): H1[] => SYNTHETIC_SERIES[name]().filter((b) => fxOpen(b.t));
const run = (bars: Bar[], tf: string) => {
  let s: State = initState(); const events: unknown[] = []; const store = new SnapshotStore(tf); const states: State[] = [];
  for (const b of bars) { const r = step(frozenV32cConfig(tf), s, b); s = r.state; events.push(...r.events); store.record(s); states.push(s); }
  return { s, events, store, states };
};

